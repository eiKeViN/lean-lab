#!/usr/bin/env python3
"""Generate a small traceable index from source docstrings and provenance keys."""
from pathlib import Path
import argparse,json,re
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]

def render(corpus_path):
    data=json.loads((HERE/'lemma-materials.json').read_text())
    policy=json.loads((HERE/'lemma-pilot.json').read_text())
    plan=json.loads((ROOT/'reports/evidence/lemma-granularity/plan.json').read_text())
    expansion=json.loads((ROOT/'reports/evidence/lemma-granularity-expansion/plan.json').read_text())
    comparison=json.loads((ROOT/'reports/evidence/lemma-granularity-comparison/plan.json').read_text())
    library=json.loads((ROOT/'reports/evidence/lemma-granularity-library/plan.json').read_text())
    samples={x['id']:x for x in plan['samples']+expansion['samples']+comparison['samples']+library['samples']}
    corpus=json.loads(Path(corpus_path).read_text());docs={x['name']:x['doc'] for x in corpus['records']}
    if {x['declaration'] for x in data['entries']}!=set(policy['additions']):raise RuntimeError('Incomplete lemma index')
    lines=['# Extracted lemma materials','','Generated by `render_lemma_index.py`; Lean docstrings are the explanation source.',
      'The JSON index maintains only provenance, keywords and decisions. No per-file',
      'Markdown specification, vector database or duplicate formal signature is maintained.','',
      'Forty-five original-client/helper relationships, two second old-client uses and',
      'one helper-to-helper relationship plus two existing-API reuses are verified in kernel proof expressions by',
      'PilotChecks. All old clients are within the planned samples; outside-sample',
      'production reuse is **0**. Focused examples are applicability tests, not reuse.',
      'The library round adds twenty-four lemmas and rewrites twenty-one old proofs.', '']
    for row in data['entries']:
        name=row['declaration'];sample=samples[row['original_site']];parent_path=sample['path'];path=library.get('helper_sources',{}).get(name,parent_path);text=(HERE/path).read_text();short=name.rsplit('.',1)[-1]
        marker='theorem '+short;pos=text.index(marker);start=text.rfind('/--',0,pos);end=text.index('-/',start)
        if text[end+2:pos].strip():raise RuntimeError('Unexpected docstring attachment: '+name)
        raw=text[start+3:end].strip();doc=docs.get(name,'')
        normalize=lambda s:re.sub(r'\s+',' ',s).strip()
        if not doc or normalize(raw)!=normalize(doc):raise RuntimeError('Stale/missing compiled docstring: '+name)
        line=text[:pos].count('\n')+1
        parent_text=(HERE/parent_path).read_text()
        parent_pos=parent_text.index('theorem '+sample['declaration'].rsplit('.',1)[-1])
        parent_line=parent_text[:parent_pos].count('\n')+1
        base=(plan['base_commit'] if row['original_site'].startswith('S') else
            expansion['starting_commit'] if row['original_site'].startswith('E') else comparison['starting_commit'] if row['original_site'].startswith('P') else library['starting_commit'])
        lines+=['## '+row['candidate']+' — `'+short+'`','',
          '[`'+name+'`]('+path+'#L'+str(line)+')','',normalize(doc),'',
          'Keywords: '+', '.join(row['keywords'])+'.',
          'Source client: [`'+sample['declaration']+'`]('+parent_path+'#L'+str(parent_line)+') ('+row['original_site']+').',
          '[Original file](https://github.com/eiKeViN/lean-lab/blob/'+base+'/experiments/kl-for-mathlib/'+parent_path+') at `'+base[:8]+'`.',
          'Reason: '+row['reason']]
        if row.get('helper_consumers'):
            lines+=['Observed helper consumers: '+', '.join('`'+n+'`' for n in row['helper_consumers'])+'.']
        second=row['second_sites']
        lines+=['Observed second production sites: '+(', '.join('`'+samples[x]['declaration']+'` ('+x+')' for x in second) if second else 'none')+'.',
          'Applicability checks: '+('; '.join(row['applicability_tests']) if row['applicability_tests'] else 'no separate example in this pilot')+'.','']
    lines+=['## Existing API reused in the library round','',
      '[`Hilbert.hasSum_shift_coeff`](ForMathlib/Algebra/Module/Graded/Hilbert/Numerator.lean#L13)',
      'is the existing integer-graded weighted-sequence shift API. Its new old-client',
      'uses are `scalar_value` and `shifted_image_value`; no duplicate shift lemma',
      'is retained. This lookup note does not add a docstring to the unchanged theorem.','',
      'Declined: C3/C4/C7/C10 wrap existing simp, equality, nonzero-power or arithmetic',
      'automation steps; C9 adds another context-heavy endpoint wrapper without a',
      'separate consumer. See the fixed plan and pilot report.','',
      'Expansion declines: scalar base-change API relocation, direct character simp branches,',
      'scalar wrappers for the triple-product calculation, and model-sum API redesign.',
      'See the expansion plan/report for individual reasons.','',
      'Comparison declines: upper-kernel set wrappers, elementary positivity/cancellation,',
      'an extra chosen-basis polynomial wrapper, and changing previously frozen APIs.',
      'See the comparison plan/report for reasons.','',
      'Library-round deferrals: broader adjoint/tensor APIs, local simp wrappers,',
      'degree-bound arithmetic and context-heavy support/generator constructions.',
      'See the coverage register for targeted reading versus inventory-only deferral.','',
      'Reproduce retrieval with SemanticCorpus.lean and semantic_search.py; see README.']
    return '\n'.join(lines)+'\n'

def main():
    p=argparse.ArgumentParser();p.add_argument('corpus');p.add_argument('--check',action='store_true');args=p.parse_args();text=render(args.corpus);target=HERE/'LEMMA_INDEX.md'
    if args.check:
        if not target.exists() or target.read_text()!=text:raise RuntimeError('Stale generated lemma index')
    else:target.write_text(text)
    print('Forty-five indexed lemmas match their compiled source docstrings.')
if __name__=='__main__':main()
