#!/usr/bin/env python3
"""Generate a small traceable index from source docstrings and provenance keys."""
from pathlib import Path
import argparse,json,re
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]

def render(corpus_path):
    data=json.loads((HERE/'lemma-materials.json').read_text())
    policy=json.loads((HERE/'lemma-pilot.json').read_text())
    plan=json.loads((ROOT/'reports/evidence/lemma-granularity/plan.json').read_text())
    expansion=json.loads((ROOT/'reports/evidence/lemma-granularity-expansion/plan.json').read_text())
    samples={x['id']:x for x in plan['samples']+expansion['samples']}
    corpus=json.loads(Path(corpus_path).read_text());docs={x['name']:x['doc'] for x in corpus['records']}
    if {x['declaration'] for x in data['entries']}!=set(policy['additions']):raise RuntimeError('Incomplete lemma index')
    lines=['# Extracted lemma materials','','Generated by `render_lemma_index.py`; Lean docstrings are the explanation source.',
      'The JSON index maintains only provenance, keywords and decisions. No per-file',
      'Markdown specification, vector database or duplicate formal signature is maintained.','',
      'Thirteen original-client/helper relationships and one second production relationship',
      'are verified in kernel',
      'proof expressions by PilotChecks. Both consumers of the shared coordinate lemma',
      'are among the first four planned samples; outside-sample production reuse is **0**.',
      'Focused examples are applicability tests, not production reuse. The expansion adds',
      'five samples and eight lemmas chosen for independent mathematical responsibility.','']
    for row in data['entries']:
        name=row['declaration'];sample=samples[row['original_site']];path=sample['path'];text=(HERE/path).read_text();short=name.rsplit('.',1)[-1]
        marker='theorem '+short;pos=text.index(marker);start=text.rfind('/--',0,pos);end=text.index('-/',start)
        if text[end+2:pos].strip():raise RuntimeError('Unexpected docstring attachment: '+name)
        raw=text[start+3:end].strip();doc=docs.get(name,'')
        normalize=lambda s:re.sub(r'\s+',' ',s).strip()
        if not doc or normalize(raw)!=normalize(doc):raise RuntimeError('Stale/missing compiled docstring: '+name)
        line=text[:pos].count('\n')+1
        parent_pos=text.index('theorem '+sample['declaration'].rsplit('.',1)[-1])
        parent_line=text[:parent_pos].count('\n')+1
        base=plan['base_commit'] if row['original_site'].startswith('S') else expansion['starting_commit']
        lines+=['## '+row['candidate']+' — `'+short+'`','',
          '[`'+name+'`]('+path+'#L'+str(line)+')','',normalize(doc),'',
          'Keywords: '+', '.join(row['keywords'])+'.',
          'Source client: [`'+sample['declaration']+'`]('+path+'#L'+str(parent_line)+') ('+row['original_site']+').',
          '[Original file](https://github.com/eiKeViN/lean-lab/blob/'+base+'/experiments/kl-for-mathlib/'+path+') at `'+base[:8]+'`.',
          'Reason: '+row['reason']]
        second=row['second_sites']
        lines+=['Observed second production sites: '+(', '.join('`'+samples[x]['declaration']+'` ('+x+')' for x in second) if second else 'none')+'.',
          'Applicability checks: '+('; '.join(row['applicability_tests']) if row['applicability_tests'] else 'no separate example in this pilot')+'.','']
    lines+=['Declined: C3/C4/C7/C10 wrap existing simp, equality, nonzero-power or arithmetic',
      'automation steps; C9 adds another context-heavy endpoint wrapper without a',
      'separate consumer. See the fixed plan and pilot report.','',
      'Expansion declines: scalar base-change API relocation, direct character simp branches,',
      'scalar wrappers for the triple-product calculation, and model-sum API redesign.',
      'See the expansion plan/report for individual reasons.','',
      'Reproduce retrieval with SemanticCorpus.lean and semantic_search.py; see README.']
    return '\n'.join(lines)+'\n'

def main():
    p=argparse.ArgumentParser();p.add_argument('corpus');p.add_argument('--check',action='store_true');args=p.parse_args();text=render(args.corpus);target=HERE/'LEMMA_INDEX.md'
    if args.check:
        if not target.exists() or target.read_text()!=text:raise RuntimeError('Stale generated lemma index')
    else:target.write_text(text)
    print('Thirteen indexed lemmas match their compiled source docstrings.')
if __name__=='__main__':main()
